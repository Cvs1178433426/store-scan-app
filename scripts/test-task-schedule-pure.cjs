const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('/opt/nvm/versions/node/v22.16.0/lib/node_modules/typescript');
const source = fs.readFileSync('apps/api/src/lib/taskSchedule.ts', 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const cjs = { exports: {} };
vm.runInNewContext(`(function(exports,require,module){${output}\n})(module.exports,require,module);`, { module: cjs, require, console, Date, Intl, Object, Math, RegExp });
const { dateOnly, isTemplateDue, localDateInTimeZone, dueAtForDate } = cjs.exports;
const d = (value) => new Date(`${value}T00:00:00.000Z`);
assert.equal(dateOnly('2026-02-30'), null);
assert.equal(localDateInTimeZone(new Date('2026-08-28T01:30:00Z'), 'America/Los_Angeles').toISOString().slice(0, 10), '2026-08-27');
assert.equal(dueAtForDate(d('2026-08-28'), '16:30', 'America/New_York').toISOString(), '2026-08-28T20:30:00.000Z');
assert.equal(dueAtForDate(d('2026-03-08'), '01:30', 'America/New_York').toISOString(), '2026-03-08T06:30:00.000Z');
assert.equal(dueAtForDate(d('2026-03-08'), '02:30', 'America/New_York'), null, 'nonexistent DST wall time must not silently become a different time');
assert.equal(dueAtForDate(d('2026-03-08'), '03:30', 'America/New_York').toISOString(), '2026-03-08T07:30:00.000Z');
assert.equal(dueAtForDate(d('2026-11-01'), '01:30', 'America/New_York').toISOString(), '2026-11-01T05:30:00.000Z');
const monthEnd = { recurrence:'MONTHLY', startDate:d('2026-01-01'), endDate:null, weeklyDay:null, monthlyDay:31 };
assert.equal(isTemplateDue(monthEnd, d('2026-02-28')), true);
console.log('task schedule pure tests passed');
